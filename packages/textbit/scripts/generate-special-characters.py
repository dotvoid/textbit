"""
Generate lib/components/SpecialCharacters/characters.ts - the default set of
special characters with their English Unicode names.

    python3 scripts/generate-special-characters.py

Names come from Python's unicodedata, so the Unicode version is whatever the
running Python ships. Code points without a name (unassigned) are skipped.
"""
import unicodedata
from pathlib import Path

# The ranges of the original special characters grid, without plain ASCII
# (already on the keyboard), plus the spaces that matter for typography but are
# impossible to see: no-break, thin and narrow no-break space.
RANGES = [
    (0x00A0, 0x00A0), (0x00A1, 0x00AC), (0x00AE, 0x024F), (0x02B0, 0x02FF),
    (0x0370, 0x0377), (0x037A, 0x037F), (0x0384, 0x038A), (0x038C, 0x038C),
    (0x038E, 0x03FF), (0x2009, 0x2009), (0x2010, 0x2027), (0x202F, 0x202F),
    (0x2030, 0x205E), (0x2070, 0x2071), (0x2074, 0x208E), (0x2090, 0x2094),
    (0x20A0, 0x20BF), (0x2100, 0x214E), (0x2150, 0x2186), (0x2189, 0x2189),
    (0x2200, 0x22FF),
]

OUT = Path(__file__).resolve().parent.parent / 'lib/components/SpecialCharacters/characters.ts'


def display_name(name: str) -> str:
    """'LATIN CAPITAL LETTER A WITH GRAVE' -> 'Latin capital letter A with grave'"""
    words = name.split(' ')
    capital = 'CAPITAL' in words
    out = [w if len(w) == 1 and capital else w.lower() for w in words]
    text = ' '.join(out)
    return text[0].upper() + text[1:]


def main() -> None:
    rows, skipped = [], []
    for start, end in RANGES:
        for cp in range(start, end + 1):
            try:
                name = unicodedata.name(chr(cp))
            except ValueError:
                skipped.append(f'{cp:04X}')
                continue
            rows.append((f'{cp:04X}', display_name(name)))

    rows.sort(key=lambda r: int(r[0], 16))
    lines = [
        '// Generated by scripts/generate-special-characters.py - do not edit by hand.',
        f'// English names from the Unicode {unicodedata.unidata_version} character database.',
        '',
        '/** [code point in hex, English name] */',
        'export const SPECIAL_CHARACTERS: ReadonlyArray<readonly [string, string]> = [',
        *[f"  ['{hex_}', '{name}']," for hex_, name in rows],
        ']',
        '',
    ]
    lines[-3] = lines[-3].rstrip(',')
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(lines), encoding='utf-8')
    print(f'{len(rows)} characters written to {OUT.name}, skipped unassigned: {", ".join(skipped) or "none"}')


if __name__ == '__main__':
    main()
